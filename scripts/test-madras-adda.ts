import assert from 'node:assert/strict';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { load } from 'cheerio';
import { venueFit } from '../components/venues/figma/venueFit';
import { HostSpaceEditor } from '../components/venues/HostSpaceEditor';
import { HostVenueDetailsEditor } from '../components/venues/HostVenueDetailsEditor';
import { parseHostVenueDetails } from '../lib/venueHostDetails';
import { parseHostSpaceDetails } from '../lib/venueHostSpaceValidation';
import { publicSpacePricing, quoteSpace } from '../lib/venuePricing';
import { rateForSpace } from '../lib/venues';
import type { CatalogVenue } from '../lib/venueCatalog';

const config = { minHours:2,markupBasisPoints:0,packages:[{id:'six-hours',name:'Six-hour booking',hours:6,basePrice:11000}] };
const space = {rowId:1,id:'event-room',name:'Madras Adda Event Room',eyebrow:'For small gatherings',description:'Art workshops, pottery events and discussions.',capacity:'15–20 people',maxGuests:20,image:'/api/poster/1',photos:['/api/poster/1'],amenities:['Wi-Fi','Projector','Speakers'],communityRate:2000,productionRate:3000,minimumFoodSpend:null,sortOrder:0,pricing:publicSpacePricing(2000,config,3000),pricingConfig:config};
const venue:CatalogVenue = {id:1,slug:'madras-adda',name:'Madras Adda',area:'Mylapore',city:'Chennai',address:'Fixture address',summary:'Tech gatherings, social gatherings, book readings, art workshops, pottery events and discussion groups.',status:'live',rating:null,ratingCount:null,ratingUrl:null,phone:null,mapUrl:null,mapEmbedUrl:null,photos:['/api/poster/1'],amenities:['Wi-Fi','Air conditioning','Projector','Speakers','Lift access'],policies:['Keep clean.'],spaces:[space]};
assert.equal(rateForSpace(space,'Tech meetup'),2000);
assert.equal(rateForSpace(space,'Photoshoot'),3000,'production rate remains independently editable');
assert.equal(quoteSpace(3000,config,2).total,6000);
assert.equal(quoteSpace(2000,config,6,'six-hours').total,11000);
const fit=venueFit(venue)!;
assert.ok(fit.rows.some(row=>row.name==='Social gathering'));
assert.ok(fit.rows.some(row=>row.name==='Tech meetup'));
assert.deepEqual(new Set(fit.rows.map(row=>row.name)),new Set(['Social gathering','Tech meetup','Art workshop','Pottery workshop','Book reading']),'owner-confirmed event uses are shown rather than unrelated dance/product suggestions');
assert.ok(fit.rows.every(row=>!row.note.includes('Work tables')),'pottery welcome never invents work tables');
assert.ok(fit.rows.every(row=>row.score>=0&&row.score<=10));
assert.equal(venueFit({...venue,spaces:[]}),null);
const details={name:'Madras Adda',area:'Mylapore',city:'Chennai',address:'Address',summary:'Summary',phone:'',mapUrl:'',amenities:[],policies:[]};
assert.equal(typeof parseHostVenueDetails(details),'object');
for(const extra of [{slug:'time-cafe'},{status:'live'},{rating:5},{commission:0},{mapUrl:'https://attacker.invalid'}]) assert.equal(typeof parseHostVenueDetails({...details,...extra}),'string');
const hostSpace={name:space.name,eyebrow:'',description:'',maxGuests:20,communityRate:2000,productionRate:3000,photos:space.photos,packagePricing:{minHours:2,packages:config.packages}};
assert.equal(typeof parseHostSpaceDetails(hostSpace),'object');
assert.equal(typeof parseHostSpaceDetails({...hostSpace,packagePricing:{...config}}),'string');
assert.equal(typeof parseHostSpaceDetails({...hostSpace,packagePricing:{minHours:2,packages:[{...config.packages[0],hours:1}]}}),'string');
const html=load(renderToStaticMarkup(createElement(HostSpaceEditor,{space,onSaved(){},onCancel(){}})));
assert.match(html.text(),/commission is deducted/);
assert.equal(html('input[value="11000"]').length,1);
assert.equal(html('input[value="2"]').length,1);
const form=load(renderToStaticMarkup(createElement(HostVenueDetailsEditor,{venue:{...venue,spaces:[space]},onSaved(){}})));
assert.match(form.text(),/House policies/);
assert.match(form.text(),/Publish venue details/);
assert.equal(form('input[type="tel"]').length,1);
console.log('PASS Madras Adda: honest event fit, ₹2,000 hourly / ₹11,000 six hours, commission deduction, separate production rate, editable host listing/offers, protected agreement and identity fields.');
